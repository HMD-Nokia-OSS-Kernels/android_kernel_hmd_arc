static int umb9230s_send_cmds(struct umb9230s_device *umb9230s, void *data)
{
	uint16_t len;
	struct dsi_cmd_desc *cmds = data;

	if ((cmds == NULL) || (umb9230s == NULL))
		return -1;

	for (; cmds->data_type != CMD_END;) {
		len = (cmds->wc_h << 8) | cmds->wc_l;
		umb9230s_dsi_tx_gen_write(umb9230s, cmds->payload, len);
		if (cmds->wait)
			msleep(cmds->wait);
		cmds = (struct dsi_cmd_desc *)(cmds->payload + len);
	}
	return 0;
}

static int nt36672e_init(void)
{
	struct sprd_dsi *dsi = &dsi_device;
	struct sprd_dphy *dphy = &dphy_device;
	struct umb9230s_device *umb9230s;

	if (hr_type != HR_TYPE_UMB9230s) {
		pr_info("no umb9230s, skip\n");
		return -1;
	}

	mipi_dsi_lp_cmd_enable(dsi, true);

	umb9230s = &umb9230s_dev;
	umb9230s_dsi_tx_lp_cmd_enable(umb9230s, true);
	umb9230s_send_cmds(umb9230s, init_data);
	umb9230s_dsi_tx_set_work_mode(umb9230s, SPRD_MIPI_MODE_VIDEO);
	umb9230s_dsi_tx_state_reset(umb9230s);
	umb9230s_phy_tx_hs_clk_en(umb9230s, true);

	mipi_dsi_set_work_mode(dsi, SPRD_MIPI_MODE_VIDEO);
	//mipi_dsi_lp_cmd_enable(dsi, true);
	mipi_dsi_state_reset(dsi);

	return 0;
}

static int nt36672e_readid(struct panel_info *info)
{
	struct sprd_dsi *dsi = &dsi_device;
	uint8_t read_buf[5] = {0};
	int i, ret = 0;
	u8 bias_config[4][2] = {{0x00, 0x0A}, {0x01, 0x0A}, {0x03, 0x03}, {0xff, 0x80}};
	struct umb9230s_device *umb9230s;

	if (hr_type != HR_TYPE_UMB9230s) {
		pr_info("no umb9230s, skip\n");
		return -1;
	}

	umb9230s = &umb9230s_dev;
	umb9230s_phy_rx_wait_clklane_stop_state(umb9230s);
	mipi_dphy_hs_clk_en(&dphy_device, true);
	mipi_dsi_lp_cmd_enable(dsi, true);

	umb9230s_dsi_tx_lp_cmd_enable(umb9230s, true);
	umb9230s_dsi_tx_set_max_return_size(umb9230s, 5);
	umb9230s_dsi_tx_dcs_read(umb9230s, 0x04, read_buf, 5);

	if((0x41 == read_buf[0]) && (0x80 == read_buf[1]) &&
	   (0x00 == read_buf[2])) {
		pr_info("nt36672e read id success!\n");

		if (info->need_config_bias) {
			for (i = 0; i < sizeof(bias_config)/sizeof(bias_config[0]); i++) {
				ret = i2c_send(info->lcd_i2c_bus_num, info->lcd_i2c_slaver_addr, (unsigned char *)bias_config[i], ARRAY_SIZE(bias_config[i]));
				if (ret < 0) {
					pr_err("config lcd i2c bias power failed\n");
					break;
				}
			}
		}

		return 0;
    }
	pr_err("nt36672e read id failed:0x%x,0x%x,0x%x,0x%x\n",read_buf[0],read_buf[1],read_buf[2],read_buf[3]);
	return -1;
}

static int nt36672e_power(int on)
{
	if (on) {
#ifdef CONFIG_LCM_GPIO_AVDDEN
                sprd_gpio_request(CONFIG_LCM_GPIO_AVDDEN);
                sprd_gpio_direction_output(CONFIG_LCM_GPIO_AVDDEN, 1);
                mdelay(20);
#endif
#ifdef CONFIG_LCM_GPIO_AVEEEN
                sprd_gpio_request(CONFIG_LCM_GPIO_AVEEEN);
                sprd_gpio_direction_output(CONFIG_LCM_GPIO_AVEEEN, 1);
                mdelay(20);
#endif

		sprd_gpio_request(CONFIG_LCM_GPIO_RSTN);
		sprd_gpio_direction_output(CONFIG_LCM_GPIO_RSTN, 1);
		mdelay(15);
		sprd_gpio_direction_output(CONFIG_LCM_GPIO_RSTN, 0);
		mdelay(15);
		sprd_gpio_direction_output(CONFIG_LCM_GPIO_RSTN, 1);
		mdelay(20);
	} else {
		sprd_gpio_direction_output(CONFIG_LCM_GPIO_RSTN, 0);
		mdelay(5);
	}

	return 0;
}

